/*
 * ============================================================
 * SÍGALE — PURCHASES CONTROLLER (public purchase flow)
 * The transactional heart of the system (ADR-0001 §6).
 *
 * Every inventory path uses pool.getConnection() + beginTransaction()
 * + SELECT ... FOR UPDATE so concurrent reservations on the same stage
 * serialize and exactly one wins the last spot (the other gets 409).
 * NEVER pool.query for these flows. conn.release() always in finally.
 *
 * Security (plan §6): explicit column lists on the public INSERT (no
 * `SET ?` mass-assignment — an attacker must not be able to force
 * status='confirmed'); parameterized everywhere; orderId is a 3-digit
 * folio unique PER event, generated by retry-on-duplicate.
 *
 * Hold semantics (decision #4): reservationExpiresAt = createdAt + 24h
 * (real hold). The 20-minute countdown is frontend copy only.
 *
 * QR rule: validationHash/tickets are returned ONLY when status =
 * 'confirmed'. The QR is generated client-side and never stored.
 * ============================================================
 */

import pool from '../db.js';
import { sendErrorEmail } from '../utils/emailNotifier.js';
import { BOGOTA, UTC } from '../utils/time.js';

const MAX_TICKETS_PER_PURCHASE = 6;
const ORDER_ID_RETRIES = 25; // 3-digit space is 900 values; ample for aforo ~200

/** Random 3-digit folio as a zero-padded string ('001'..'999'). */
function randomOrderId() {
  return String(Math.floor(Math.random() * 900) + 100); // 100..999 (3 digits)
}

/**
 * POST /api/purchases  (public)
 * Reserve `quantity` spots on a stage and open a pending_payment purchase.
 * Idempotent on idempotencyKey: a retry with the same key returns the
 * original purchase instead of double-reserving.
 */
export const createPurchase = async (req, res) => {
  const { eventId, stageId, quantity, deliveryMethod, deliveryContact, idempotencyKey } = req.body;

  // Basic validation (explicit — never trust the body shape).
  if (!eventId || !stageId || !quantity || !deliveryMethod || !deliveryContact) {
    return res.status(400).json({ message: 'Faltan campos obligatorios de la compra' });
  }
  const qty = Number(quantity);
  if (!Number.isInteger(qty) || qty < 1 || qty > MAX_TICKETS_PER_PURCHASE) {
    return res.status(400).json({ message: `Cantidad inválida (1–${MAX_TICKETS_PER_PURCHASE})` });
  }
  if (!['email', 'whatsapp'].includes(deliveryMethod)) {
    return res.status(400).json({ message: 'Método de entrega inválido' });
  }

  const conn = await pool.getConnection();
  try {
    await conn.beginTransaction();

    // Idempotency: if this key already produced a purchase, return it.
    if (idempotencyKey) {
      const [[existing]] = await conn.query(
        'SELECT orderId FROM purchases WHERE idempotencyKey = ? LIMIT 1',
        [idempotencyKey],
      );
      if (existing) {
        await conn.commit();
        return res.json({ orderId: existing.orderId, idempotent: true });
      }
    }

    // 1. Lock the stage row. Other reservations on this stage wait here.
    const [[stage]] = await conn.query(
      "SELECT id, eventId, price, totalQuantity, soldQuantity, reservedQuantity " +
        "FROM ticket_stages WHERE id = ? AND status = 'active' FOR UPDATE",
      [stageId],
    );
    if (!stage) {
      await conn.rollback();
      return res.status(409).json({ message: 'La etapa no está disponible' });
    }

    // 2. Availability check (in the app, under the lock).
    const available = stage.totalQuantity - stage.soldQuantity - stage.reservedQuantity;
    if (available < qty) {
      await conn.rollback();
      return res.status(409).json({ message: 'Cupos insuficientes' });
    }

    // 3. Firm reservation.
    await conn.query(
      'UPDATE ticket_stages SET reservedQuantity = reservedQuantity + ? WHERE id = ?',
      [qty, stageId],
    );

    const totalAmount = Number(stage.price) * qty;

    // 4. Insert the purchase with a unique 3-digit folio (retry on collision).
    let orderId = null;
    let lastErr = null;
    for (let i = 0; i < ORDER_ID_RETRIES; i++) {
      const candidate = randomOrderId();
      try {
        await conn.query(
          `INSERT INTO purchases
             (eventId, stageId, quantity, totalAmount, orderId, deliveryMethod, deliveryContact,
              status, idempotencyKey, reservationExpiresAt)
           VALUES (?, ?, ?, ?, ?, ?, ?, 'pending_payment', ?, DATE_ADD(UTC_TIMESTAMP(), INTERVAL 24 HOUR))`,
          [eventId, stageId, qty, totalAmount, candidate, deliveryMethod, deliveryContact, idempotencyKey || null],
        );
        orderId = candidate;
        break;
      } catch (err) {
        // Folio collision (uqPurchaseOrderId) → try another. Idempotency
        // collision (uqPurchaseIdem) → another request won the race; surface it.
        if (err.code === 'ER_DUP_ENTRY' && /uqPurchaseIdem/.test(err.sqlMessage || '')) {
          const [[existing]] = await conn.query(
            'SELECT orderId FROM purchases WHERE idempotencyKey = ? LIMIT 1',
            [idempotencyKey],
          );
          await conn.commit();
          return res.json({ orderId: existing?.orderId, idempotent: true });
        }
        if (err.code === 'ER_DUP_ENTRY') { lastErr = err; continue; }
        throw err;
      }
    }
    if (!orderId) {
      await conn.rollback();
      throw lastErr || new Error('No se pudo asignar un número de orden (folios agotados)');
    }

    await conn.commit();
    res.status(201).json({ orderId, totalAmount });
  } catch (error) {
    await conn.rollback();
    sendErrorEmail(req, error, 'createPurchase');
    return res.status(500).json({ message: error.message, sqlMessage: error.sqlMessage });
  } finally {
    conn.release();
  }
};

/**
 * POST /api/purchases/:orderId/submitted  (public)
 * Buyer tapped "Ya realicé el pago" → pending_payment -> payment_submitted.
 * NOTE: orderId is unique per event; with a single active event this is
 * unambiguous. When multiple events run, also scope by eventId.
 */
export const submitPayment = async (req, res) => {
  const conn = await pool.getConnection();
  try {
    await conn.beginTransaction();

    const [[purchase]] = await conn.query(
      'SELECT id, status FROM purchases WHERE orderId = ? ORDER BY createdAt DESC LIMIT 1 FOR UPDATE',
      [req.params.orderId],
    );
    if (!purchase) {
      await conn.rollback();
      return res.status(404).json({ message: 'Compra no encontrada' });
    }
    // Only a still-pending purchase can be marked submitted (idempotent if already).
    if (purchase.status === 'payment_submitted') {
      await conn.commit();
      return res.json({ orderId: req.params.orderId, status: 'payment_submitted' });
    }
    if (purchase.status !== 'pending_payment') {
      await conn.rollback();
      return res.status(409).json({ message: `La compra está en estado '${purchase.status}'` });
    }

    await conn.query("UPDATE purchases SET status = 'payment_submitted' WHERE id = ?", [purchase.id]);
    await conn.commit();
    res.json({ orderId: req.params.orderId, status: 'payment_submitted' });
  } catch (error) {
    await conn.rollback();
    sendErrorEmail(req, error, 'submitPayment');
    return res.status(500).json({ message: error.message });
  } finally {
    conn.release();
  }
};

/**
 * GET /api/purchases/:orderId  (public)
 * Returns the purchase status. Tickets (with validationHash for the QR)
 * are included ONLY when confirmed.
 */
export const getPurchaseByOrderId = async (req, res) => {
  try {
    const [[purchase]] = await pool.query(
      `SELECT p.id, p.orderId, p.quantity, p.totalAmount, p.status, p.deliveryMethod,
              CONVERT_TZ(p.createdAt, '${UTC}', '${BOGOTA}') AS createdAt,
              CONVERT_TZ(p.reservationExpiresAt, '${UTC}', '${BOGOTA}') AS reservationExpiresAt,
              s.name AS stageName, s.price AS stagePrice,
              e.id AS eventId, e.name AS eventName
       FROM purchases p
       JOIN ticket_stages s ON s.id = p.stageId
       JOIN events e ON e.id = p.eventId
       WHERE p.orderId = ? ORDER BY p.createdAt DESC LIMIT 1`,
      [req.params.orderId],
    );
    if (!purchase) {
      return res.status(404).json({ message: 'Compra no encontrada' });
    }

    let tickets = [];
    if (purchase.status === 'confirmed') {
      const [rows] = await pool.query(
        'SELECT id, holderName, holderIdNumber, validationHash, isUsed FROM tickets WHERE purchaseId = ?',
        [purchase.id],
      );
      tickets = rows; // client builds the QR from validationHash; image never stored
    }

    res.json({ ...purchase, tickets });
  } catch (error) {
    sendErrorEmail(req, error, 'getPurchaseByOrderId');
    return res.status(500).json({ message: error.message });
  }
};

/**
 * GET /api/recover?contact=  (public, rate-limited at the route)
 * Anti-enumeration: returns at most the folios for an exact contact match,
 * and never reveals whether a contact "exists" beyond the returned list.
 */
export const recoverByContact = async (req, res) => {
  try {
    const contact = (req.query.contact || '').trim();
    if (!contact) return res.json({ orders: [] });

    const [rows] = await pool.query(
      `SELECT orderId, status,
              CONVERT_TZ(createdAt, '${UTC}', '${BOGOTA}') AS createdAt
       FROM purchases WHERE deliveryContact = ? ORDER BY createdAt DESC LIMIT 20`,
      [contact],
    );
    res.json({ orders: rows });
  } catch (error) {
    sendErrorEmail(req, error, 'recoverByContact');
    return res.status(500).json({ message: error.message });
  }
};
